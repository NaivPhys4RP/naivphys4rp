GRAMMAR_FILE = 'terminals.lark'
MAX_DEPTH = 4
N_SAMPLES = 6
START_SYMBOL='joint_definition'

def extract_prob_terminals(grammar_text: str):
    pattern = re.compile(r'(PROB\d+)\s*:\s*"([0-9.]+)"')
    return {m.group(1): float(m.group(2)) for m in pattern.finditer(grammar_text)}

def normalize_expansion(expansion):
    return ' '.join(sym.name if isinstance(sym, (Terminal, NonTerminal)) else str(sym)
                    for sym in expansion)

def extract_rule_probabilities_from_grammar(grammar_file: str, start_symbol: str = START_SYMBOL):
    grammar_text = Path(HOME_PATH+grammar_file).read_text()
    prob_map = extract_prob_terminals(grammar_text)
    parser = Lark.open(grammar_file, parser='lalr', start=start_symbol, rel_to=HOME_PATH, import_paths=[HOME_PATH])
    rules = parser.rules
    terminals = {t.name: t for t in parser.terminals}

    rule_weights = {}
    for rule in rules:
        origin = rule.origin.name
        expansion = rule.expansion
        prob_value = 1.0
        #print(rule,origin)

        if expansion and isinstance(expansion[-1], Terminal) and expansion[-1].name.startswith("PROB"):
            prob_symbol = expansion[-1].name
            prob_value = prob_map.get(prob_symbol, 1.0)
            expansion = expansion[:-1]

        key = (origin, normalize_expansion(expansion))
        rule_weights.setdefault(origin, []).append((rule, prob_value))

    rule_probs = {}
    for origin, rule_list in rule_weights.items():
        total = sum(weight for _, weight in rule_list)
        rule_probs[origin] = [(rule, weight / total) for rule, weight in rule_list]
    return rule_probs, terminals, parser

class GrammarGenerator:
    def __init__(self, rule_probs, terminals, parser, max_depth=MAX_DEPTH):
        self.rule_probs = rule_probs
        self.terminals = terminals
        self.parser = parser
        self.max_depth = max_depth
        self.enum_cache = self._build_enum_cache()
        self.terminal_generators = self._build_terminal_generators()
        self.repetition_rules = self._detect_repetition_rules()

    def _detect_repetition_rules(self):
        """Detect rules generated by '*' or '+' operators."""
        return {r.origin.name for r in self.parser.rules if "_star_" in r.origin.name or "_plus_" in r.origin.name}

    def _build_enum_cache(self):
        enum_map = {}
        for name, terminal in self.terminals.items():
            pattern = terminal.pattern.value
            literals = re.findall(r'"(.*?)"', pattern)
            if literals:
                enum_map[name] = [f'"{lit}"' for lit in literals]
        return enum_map

    def _build_terminal_generators(self):
        return {
            "TEXTURE_VALUE": lambda: random.choice(["\"PATTERN_T\"", "\"SOLID_T\"", "\"GRADIENT_T\"", "\"PICTURE_T\""]),
            "DECIMAL": lambda: f"{random.uniform(0.1, 10.0):.2f}",
            "FLOAT": lambda: f"{random.uniform(0.1, 100.0):.5f}",
            "INT": lambda: f"{random.randint(1, 100)}",
            "NUMBER": lambda: f"{random.randint(0, 100)}",
            "ESCAPED_STRING": lambda: '"' + ''.join(random.choices(string.ascii_letters, k=5)) + '"',
            "COLOR": lambda: random.choice(["\"RED\"", "\"ORANGE\"", "\"BROWN\"", "\"YELLOW\"", "\"GREEN\"", "\"BLUE\"", "\"WHITE\"", "\"GRAY\"", "\"BLACK\"", "\"VIOLET\"", "\"PINK\""]),
            "MATERIAL": lambda: random.choice(["\"PLASTIC\"", "\"WOOD\"", "\"GLASS\"", "\"STEEL\"", "\"CARTOON\"", "\"CERAMIC\""]),
            # Punctuation / JSON keys mapping ...
            "COLON": lambda: ":",
            "LBRACE": lambda: "{",
            "RBRACE": lambda: "}",
            "LBRACK": lambda: "[",
            "RBRACK": lambda: "]",
            "COMMA": lambda: ",",
        }

    def generate(self, rule_name=START_SYMBOL, depth=0):
        """Generate a word from the grammar, track derivation and probability."""
        rules_with_probs = self.rule_probs.get(rule_name)
        # Terminal
        if not rules_with_probs:
            word = self._generate_terminal(rule_name)
            return word, [("TERMINAL", rule_name, word)], 1.0

        rules, weights = zip(*rules_with_probs)
        selected_rule = random.choices(rules, weights=weights, k=1)[0]
        prob = dict(rules_with_probs)[selected_rule]

        children = []
        pieces = []

        for sym in selected_rule.expansion:
            if isinstance(sym, Terminal) and sym.name.startswith("PROB"):
                continue

            # Only apply max_depth to repetition rules
            if isinstance(sym, NonTerminal) and sym.name in self.repetition_rules and depth >= self.max_depth:
                continue

            frag, sub_deriv, sub_prob = self._generate_symbol(sym, depth + 1)
            pieces.append(frag)
            children.extend(sub_deriv)
            prob *= sub_prob

        return ''.join(pieces), [(rule_name, selected_rule.expansion, prob)] + children, prob

    def flatten_keys(self,obj):
        """
        Recursively collapse all single-key layers where a key directly wraps
        another dictionary with the same key, e.g.:
        {"aesthetics": {"aesthetics": {...}}} → {"aesthetics": {...}}
        """
        if isinstance(obj, dict):
            new_obj = {}
            for k, v in obj.items():
                v_flat = self.flatten_keys(v)
                # Keep collapsing until no redundant layer remains
                while isinstance(v_flat, dict) and len(v_flat) == 1 and k in v_flat:
                    v_flat = v_flat[k]
                new_obj[k] = v_flat
            return new_obj
        elif isinstance(obj, list):
            return [self.flatten_keys(v) for v in obj]
        else:
            return obj

    def _generate_symbol(self, symbol, depth):
        if isinstance(symbol, NonTerminal):
            return self.generate(symbol.name, depth)
        elif isinstance(symbol, Terminal):
            word = self._generate_terminal(symbol.name)
            return word, [("TERMINAL", symbol.name, word)], 1.0
        else:
            return str(symbol), [], 1.0

    def _generate_terminal(self, name):
        punctuation_map = {"LBRACE": "{", "RBRACE": "}", "LBRACK": "[", "RBRACK": "]", "COLON": ":", "COMMA": ","}
        if name in punctuation_map:
            return punctuation_map[name]
        if name in self.enum_cache:
            return random.choice(self.enum_cache[name])
        if name in self.terminal_generators:
            return self.terminal_generators[name]()
        terminal_obj = self.terminals.get(name)
        if terminal_obj and terminal_obj.pattern:
            pattern = terminal_obj.pattern.value
            m = re.fullmatch(r'"([^"]*)"', pattern)
            if m:
                return m.group(1)
        return name



